"""Feature engineering analysis: correlations, importance, and a fair comparison of feature sets.
Writes docs/feature_engineering_report.md and data/features.csv."""
import os
import pandas as pd
from xgboost import XGBClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_auc_score, f1_score

import preprocess as P


def evaluate(df, features, folds):
    """Expanding-window cross-validation by year (always train on the past, test on the future),
    plus the final 2024-2025 test. Returns mean AUC/F1 for XGBoost and Random Forest."""
    rows = []
    splits = [(df[df.date.dt.year < y], df[df.date.dt.year == y]) for y in folds]
    splits.append(P.time_split(df))
    for tr, te in splits:
        for name, m in {
            "XGB": XGBClassifier(n_estimators=200, max_depth=4, learning_rate=0.05, subsample=0.8,
                                 colsample_bytree=0.8, eval_metric="logloss", random_state=42),
            "RF": RandomForestClassifier(n_estimators=200, min_samples_leaf=3, random_state=42, n_jobs=-1),
        }.items():
            m.fit(tr[features], tr["high_risk"])
            p = m.predict_proba(te[features])[:, 1]
            rows.append({"model": name, "auc": roc_auc_score(te["high_risk"], p),
                         "f1": f1_score(te["high_risk"], p >= 0.5)})
    return pd.DataFrame(rows).groupby("model").mean().mean()


def main():
    raw = P.load_data()
    df, feats = P.build_features(raw)
    base_df, base_feats = P.build_features(raw, use_extra=False)
    os.makedirs("docs", exist_ok=True)
    out = ["# Feature engineering report\n", "Generated by `src/feature_report.py`.\n"]

    # 1. Feature groups
    groups = {
        "Calendar (month, week_of_year, monsoon)": [f for f in feats if f in ("month", "week_of_year", "monsoon")],
        "Lagged weather (1-4 weeks)": [f for f in feats if "_lag" in f and "cases" not in f],
        "Rolling weather (rain 4/8/12w, temp/humidity 4w)": [f for f in feats if f.startswith(("rain_sum", "temp_mean", "humidity_mean"))],
        "Weather combinations (temp_range, temp_x_humidity)": [f for f in feats if f in ("temp_range", "temp_x_humidity")],
        "Past cases (lags, rolling mean, trend)": [f for f in feats if f.startswith("cases_")],
        "Ward and city info": [f for f in feats if f in P.STATIC_COLS + ["city_code"]],
    }
    out.append("## Feature groups\n\n| Group | Count | Features |\n|---|---|---|")
    for k, v in groups.items():
        out.append(f"| {k} | {len(v)} | {', '.join(v)} |")
    out.append(f"\nTotal: **{len(feats)}** features. No feature uses the current week's dengue cases; case features use earlier weeks only.\n")

    # 2. Correlation with the target
    corr = df[feats + ["high_risk"]].corr()["high_risk"].drop("high_risk").sort_values(key=abs, ascending=False)
    out.append("## Strongest correlations with high-risk weeks\n\n| Feature | Correlation |\n|---|---|")
    for f, c in corr.head(10).items():
        out.append(f"| {f} | {c:.3f} |")

    # 3. Redundant features
    cm = df[feats].corr().abs()
    pairs = [(a, b, cm.loc[a, b]) for i, a in enumerate(feats) for b in feats[i + 1:] if cm.loc[a, b] > 0.95]
    out.append(f"\n## Highly correlated pairs (|r| > 0.95): {len(pairs)}\n")
    for a, b, c in sorted(pairs, key=lambda x: -x[2])[:10]:
        out.append(f"- {a} and {b}: {c:.3f}")

    # 4. Importance
    xgb = XGBClassifier(n_estimators=300, max_depth=4, learning_rate=0.05, subsample=0.8,
                        colsample_bytree=0.8, eval_metric="logloss", random_state=42)
    tr = df[df["date"].dt.year < 2021]   # before the first CV fold, so selection cannot see test years
    xgb.fit(tr[feats], tr["high_risk"])
    imp = pd.Series(xgb.feature_importances_, index=feats).sort_values(ascending=False)
    out.append("\n## Most important features (XGBoost, trained on 2016-2020 data)\n\n| Feature | Importance |\n|---|---|")
    for f, v in imp.head(10).items():
        out.append(f"| {f} | {v:.3f} |")

    # 5. Fair comparison of feature sets
    folds = [2021, 2022, 2023]
    top15 = list(imp.head(15).index)
    sets = {"Base features": (base_df, base_feats), "Base + extra features": (df, feats),
            "Top 15 by importance": (df, top15)}
    out.append("\n## Comparing feature sets\n\nMean over 3 yearly cross-validation folds (2021, 2022, 2023) "
               "and the final 2024-2025 test. Higher is better.\n\n| Feature set | Features | AUC | F1 |\n|---|---|---|---|")
    scores = {}
    for name, (d, f) in sets.items():
        s = evaluate(d, f, folds)
        scores[name] = s
        out.append(f"| {name} | {len(f)} | {s['auc']:.4f} | {s['f1']:.4f} |")
        print(f"{name:25s} features={len(f):2d} auc={s['auc']:.4f} f1={s['f1']:.4f}")

    spread = max(s["auc"] for s in scores.values()) - min(s["auc"] for s in scores.values())
    out.append(f"\n**Conclusion:** the AUC of the three sets differs by only {spread:.4f}, so the choice rests "
               "on simplicity and explainability, not accuracy. The top-15 set is a lighter option with a similar score.\n")
    open("docs/feature_engineering_report.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
    df[["date", "city", "ward_id", "dengue_cases", "high_risk"] + feats].to_csv("data/features.csv", index=False)
    print("Saved docs/feature_engineering_report.md and data/features.csv")


if __name__ == "__main__":
    main()