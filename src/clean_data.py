"""Data cleaning: validate the raw dengue dataset, fix what is wrong, write a report."""
import os
import pandas as pd

RAW_PATH = "data/dengue_dataset.csv"
CLEAN_PATH = "data/clean_dataset.csv"
REPORT_PATH = "docs/data_cleaning_report.md"

STATIC_COLS = ["population_density_sqkm", "water_logging_risk_index", "sanitation_score"]


def main():
    df = pd.read_csv(RAW_PATH)
    notes = []

    def log(title, result):
        notes.append(f"- **{title}:** {result}")
        print(f"{title}: {result}")

    log("Rows / columns", f"{df.shape[0]} / {df.shape[1]}")

    # 1. Types
    df["date"] = pd.to_datetime(df["date"], errors="coerce")
    log("Unparseable dates", int(df["date"].isna().sum()))

    # 2. Missing values
    log("Missing values (total)", int(df.isna().sum().sum()))
    num_cols = df.select_dtypes("number").columns
    df[num_cols] = df.groupby("ward_id")[list(num_cols)].transform(lambda s: s.interpolate(limit_direction="both"))

    # 3. Duplicates
    dup = int(df.duplicated(["ward_id", "date"]).sum())
    log("Duplicate ward-week rows", dup)
    df = df.drop_duplicates(["ward_id", "date"])

    # 4. Complete weekly timeline per ward
    weeks = df.groupby("ward_id")["date"].agg(["min", "max", "count"])
    expected = ((weeks["max"] - weeks["min"]).dt.days // 7 + 1)
    log("Wards with missing weeks", int((expected != weeks["count"]).sum()))

    # 5. Impossible values
    bad = {
        "negative rainfall": int((df["rainfall_mm"] < 0).sum()),
        "negative dengue cases": int((df["dengue_cases"] < 0).sum()),
        "humidity outside 0-100": int((~df["relative_humidity_pct"].between(0, 100)).sum()),
        "min_temp > avg_temp": int((df["min_temp_c"] > df["avg_temp_c"]).sum()),
        "avg_temp > max_temp": int((df["avg_temp_c"] > df["max_temp_c"]).sum()),
        "sanitation / water-logging outside 0-1": int((~df[["sanitation_score", "water_logging_risk_index"]]
                                                       .apply(lambda s: s.between(0, 1)).all(axis=1)).sum()),
    }
    for k, v in bad.items():
        log(k, v)
    df = df[(df["rainfall_mm"] >= 0) & (df["dengue_cases"] >= 0)]
    df["dengue_cases"] = df["dengue_cases"].round().astype(int)

    # 6. Consistency: each ward belongs to one city and has fixed static values
    log("Wards in more than one city", int((df.groupby("ward_id")["city"].nunique() > 1).sum()))
    log("Wards whose static columns change over time",
        int((df.groupby("ward_id")[STATIC_COLS].nunique() > 1).any(axis=1).sum()))

    # 7. Outliers: report only (they are real monsoon and outbreak weeks, so we keep them)
    for col in ["rainfall_mm", "dengue_cases"]:
        q1, q3 = df[col].quantile([0.25, 0.75])
        upper = q3 + 1.5 * (q3 - q1)
        log(f"Outliers in {col} (kept)", f"{int((df[col] > upper).sum())} rows above {upper:.1f}")

    df = df.sort_values(["ward_id", "date"]).reset_index(drop=True)
    df.to_csv(CLEAN_PATH, index=False)
    log("Clean rows saved", f"{len(df)} -> {CLEAN_PATH}")

    os.makedirs("docs", exist_ok=True)
    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        f.write("# Data cleaning report\n\nGenerated by `src/clean_data.py`.\n\n" + "\n".join(notes) + "\n")


if __name__ == "__main__":
    main()